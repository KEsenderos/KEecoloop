  var pref = 'auto';     // 'auto' か LANGS のどれか（保存する）
  var cur = 'en';        // 実際に使っている言語

  function readPref_() {
    try { var v = window.localStorage.getItem(C.STORAGE_KEY_LANG); if (v === 'auto' || LANGS.indexOf(v) >= 0) return v; } catch (e) { /* 無視 */ }
    return 'auto';
  }

  /** ブラウザの言語（navigator.languages の先頭から順に）から対応言語を選ぶ。tl（タガログ語）は fil。どれも合わなければ英語 */
  function detect() {
    var list = [];
    try { list = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || '']; } catch (e) { list = []; }
    for (var i = 0; i < list.length; i++) {
      var code = String(list[i] || '').toLowerCase().split('-')[0];
      if (code === 'tl' || code === 'fil') return 'fil';
      if (code === 'in') code = 'id';
      if (code === 'zh') {                   // 繁体字（zh-Hant・zh-TW・zh-HK・zh-MO）は zh-TW、それ以外の中国語は zh-CN
        var low = String(list[i]).toLowerCase();
        return (low.indexOf('hant') >= 0 || /-(tw|hk|mo)(-|$)/.test(low)) ? 'zh-TW' : 'zh-CN';
      }
      if (LANGS.indexOf(code) >= 0) return code;
    }
    return 'en';
  }

  function resolve_() { cur = pref === 'auto' ? detect() : pref; }

  /** 文言を返す。params の {名前} を置き換える。無い言語・キーは日本語→キー名の順で代用 */
  function t(key, params) {
    var s = DICT[cur] && DICT[cur][key];
    if (s === undefined) s = DICT.en[key];
    if (s === undefined) s = DICT.ja[key];
    if (s === undefined) return key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, function (m, name) { return params[name] !== undefined ? String(params[name]) : m; });
    }
    return s;
  }

  /** 静的なHTMLの文字を、いまの言語に書き換える（data-i18n＝本文、data-i18n-aria＝読み上げ用の名前） */
  function applyDom() {
    var i, nodes;
    nodes = document.querySelectorAll('[data-i18n]');
    for (i = 0; i < nodes.length; i++) nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
    nodes = document.querySelectorAll('[data-i18n-aria]');
    for (i = 0; i < nodes.length; i++) nodes[i].setAttribute('aria-label', t(nodes[i].getAttribute('data-i18n-aria')));
    try { document.documentElement.setAttribute('lang', cur); } catch (e) { /* 無視 */ }
  }

  function setPref(p) {
    pref = (p === 'auto' || LANGS.indexOf(p) >= 0) ? p : 'auto';
    try { window.localStorage.setItem(C.STORAGE_KEY_LANG, pref); } catch (e) { /* 無視 */ }
    resolve_();
  }

  function init() { pref = readPref_(); resolve_(); }

  RE.I18n = { LANGS: LANGS, NATIVE: NATIVE, init: init, detect: detect, t: t, applyDom: applyDom, setPref: setPref,
    getPref: function () { return pref; }, getLang: function () { return cur; } };
  init();
